CREATE TABLE learner_profiles (
 user_id VARCHAR(36) PRIMARY KEY REFERENCES app_users(id),
 game_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000) NOT NULL UNIQUE,
 display_name VARCHAR(24) NOT NULL, avatar VARCHAR(10) NOT NULL DEFAULT 'fox', avatar_image TEXT
);
CREATE TABLE learner_sessions (
 token_hash VARCHAR(64) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_users(id),
 expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_learner_sessions_user ON learner_sessions(user_id);
CREATE TABLE practice_events (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_users(id),
 client_id VARCHAR(36) NOT NULL, lesson_id VARCHAR(50) NOT NULL REFERENCES algorithms(id),
 stage INTEGER NOT NULL CHECK (stage BETWEEN 1 AND 3),
 completed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(user_id,client_id)
);
CREATE INDEX idx_practice_events_user ON practice_events(user_id,completed_at);
